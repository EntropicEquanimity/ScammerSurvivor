// The Chatter's fixed lines: one per kind of sender and chip, for a scam and for its real twin, so
// a line used when the model is off, slow or fails still answers the chip in that sender's voice.
// Code-written, short and generic (AGENTS.md rule 6): no amount, no link, no number, no real brand.
// {name} is the sender's display name. Twin lines avoid words that add a button (pay, link, code)
// and never say what the sender would never ask for (the Guard's twin rule).
